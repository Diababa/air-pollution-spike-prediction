"""
Baselines naives pour la prevision PM2.5 a 48h.

Objectif : donner un point de comparaison aux metriques XGBoost.
Un R2 ou une precision ne veulent rien dire seuls : il faut savoir
ce que fait la solution triviale sur le MEME jeu de test.

Decoupage train/test strictement chronologique (80 % / 20 %) :
le test couvre les derniers mois, jamais melanges avec l'entrainement.

Baselines regression :
  1. Persistance        : PM2.5(t+48h) = PM2.5(t)
  2. Persistance lissee : PM2.5(t+48h) = moyenne des 24 dernieres heures
  3. Climatologie       : PM2.5(t+48h) = moyenne du jeu d'entrainement

Baseline classification :
  4. Persistance du pic : pic dans 48h si PM2.5(t) depasse deja le seuil de pic
  5. Classe majoritaire : jamais de pic

Usage : python -m src.models.baseline
"""

import numpy as np
import pandas as pd
import joblib

from sklearn.metrics import (
    mean_absolute_error,
    mean_squared_error,
    r2_score,
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
)

DATA_PATH = "data/processed/train.csv"
REGRESSOR_PATH = "models/xgboost_pm25_48h.pkl"
CLASSIFIER_PATH = "models/xgboost_spike_classifier.pkl"
REPORT_PATH = "reports/baseline_comparison.md"

TRAIN_RATIO = 0.8
SPIKE_QUANTILE = 0.90         # identique a src/data/transformation.py
SPIKE_THRESHOLD_PROBA = 0.30  # identique a src/models/train_classifier.py

EXCLUDED_COLUMNS = ["datetime", "target_pm25_48h", "spike_48h"]


def load_data(path=DATA_PATH):
    df = pd.read_csv(path)
    df["datetime"] = pd.to_datetime(df["datetime"])
    return df.sort_values("datetime").reset_index(drop=True)


def chronological_split(df, ratio=TRAIN_RATIO):
    """Meme decoupage que train.py / train_classifier.py : aucun shuffle."""
    split_index = int(len(df) * ratio)
    return df.iloc[:split_index], df.iloc[split_index:]


def regression_scores(y_true, y_pred):
    return {
        "MAE": mean_absolute_error(y_true, y_pred),
        "RMSE": float(np.sqrt(mean_squared_error(y_true, y_pred))),
        "R2": r2_score(y_true, y_pred),
    }


def classification_scores(y_true, y_pred):
    return {
        "Accuracy": accuracy_score(y_true, y_pred),
        "Precision": precision_score(y_true, y_pred, zero_division=0),
        "Recall": recall_score(y_true, y_pred, zero_division=0),
        "F1": f1_score(y_true, y_pred, zero_division=0),
    }


def evaluate(df):
    train, test = chronological_split(df)

    feature_cols = [c for c in df.columns if c not in EXCLUDED_COLUMNS]
    y_test = test["target_pm25_48h"]

    # ---------- Regression ----------
    regression = {
        "Persistence (PM2.5 in 48h = PM2.5 now)":
            regression_scores(y_test, test["pm25"]),
        "Smoothed persistence (24h rolling mean)":
            regression_scores(y_test, test["rolling_mean_24"]),
        "Climatology (training mean)":
            regression_scores(
                y_test,
                np.full(len(test), train["target_pm25_48h"].mean()),
            ),
    }

    regressor = joblib.load(REGRESSOR_PATH)
    regression["XGBoost Regressor"] = regression_scores(
        y_test, regressor.predict(test[feature_cols])
    )

    # ---------- Classification ----------
    # Seuil de pic : quantile 90 du PM2.5, comme dans transformation.py
    spike_threshold = df["pm25"].quantile(SPIKE_QUANTILE)
    y_test_spike = test["spike_48h"]

    classification = {
        "Spike persistence (spike now -> spike in 48h)":
            classification_scores(
                y_test_spike,
                (test["pm25"] > spike_threshold).astype(int),
            ),
        'Always "no spike" (majority class)':
            classification_scores(y_test_spike, np.zeros(len(test), dtype=int)),
    }

    classifier = joblib.load(CLASSIFIER_PATH)
    probs = classifier.predict_proba(test[feature_cols])[:, 1]
    classification["XGBoost Classifier (threshold 0.30)"] = classification_scores(
        y_test_spike, (probs >= SPIKE_THRESHOLD_PROBA).astype(int)
    )

    context = {
        "rows_train": len(train),
        "rows_test": len(test),
        "train_period": (train["datetime"].min(), train["datetime"].max()),
        "test_period": (test["datetime"].min(), test["datetime"].max()),
        "spike_threshold": spike_threshold,
        "spike_rate_test": y_test_spike.mean(),
    }

    return regression, classification, context


def build_report(regression, classification, context):
    lines = []
    lines.append("# Baseline comparison")
    lines.append("")
    lines.append(
        "Generated by `python -m src.models.baseline`. "
        "Every metric below is computed on the **same** test set."
    )
    lines.append("")

    lines.append("## Evaluation protocol")
    lines.append("")
    lines.append(
        f"- **Chronological** {int(TRAIN_RATIO * 100)} / "
        f"{100 - int(TRAIN_RATIO * 100)} split. No shuffling, no random "
        "cross-validation: both would leak future information into training."
    )
    lines.append(
        f"- Train: {context['rows_train']:,} hours "
        f"({context['train_period'][0]:%Y-%m-%d} to "
        f"{context['train_period'][1]:%Y-%m-%d})."
    )
    lines.append(
        f"- Test: {context['rows_test']:,} hours "
        f"({context['test_period'][0]:%Y-%m-%d} to "
        f"{context['test_period'][1]:%Y-%m-%d}), strictly after the training window."
    )
    lines.append(
        f"- Spike threshold: {int(SPIKE_QUANTILE * 100)}th percentile of PM2.5 = "
        f"{context['spike_threshold']:.1f} ug/m3. Spikes are "
        f"{context['spike_rate_test'] * 100:.1f} % of the test set."
    )
    lines.append("")

    lines.append("## Regression: PM2.5 48h ahead")
    lines.append("")
    lines.append("| Model | MAE | RMSE | R2 |")
    lines.append("| ----- | --- | ---- | -- |")
    for name, scores in regression.items():
        lines.append(
            f"| {name} | {scores['MAE']:.2f} | {scores['RMSE']:.2f} "
            f"| {scores['R2']:.3f} |"
        )
    lines.append("")

    lines.append("## Classification: pollution spike within 48h")
    lines.append("")
    lines.append("| Model | Accuracy | Precision | Recall | F1 |")
    lines.append("| ----- | -------- | --------- | ------ | -- |")
    for name, scores in classification.items():
        lines.append(
            f"| {name} | {scores['Accuracy']:.3f} | {scores['Precision']:.3f} "
            f"| {scores['Recall']:.3f} | {scores['F1']:.3f} |"
        )
    lines.append("")

    return "\n".join(lines)


if __name__ == "__main__":
    df = load_data()
    regression, classification, context = evaluate(df)
    report = build_report(regression, classification, context)

    print(report)

    with open(REPORT_PATH, "w", encoding="utf-8") as f:
        f.write(report)

    print(f"Rapport sauvegarde dans {REPORT_PATH}")
